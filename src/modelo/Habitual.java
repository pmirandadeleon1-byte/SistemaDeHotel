package modelo;

public class Habitual {
    //atributo
    private double descuento;

    //constructor
    public Habitual(double descuento) {
        this.descuento = descuento;
    }

    //getter y setter
    public double getDescuento() {
        return descuento;
    }
    

    public void setDescuento(double descuento) {
        this.descuento = descuento;
    }
}
